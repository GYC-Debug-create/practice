/*
 * 第 4 题：判断点是否在矩形内（练习版）
 *
 * 来源：调研报告-1023.md 第 49 行，2025 U3D 客户端笔经（牛客）
 *   原题只留下题名，作者说自己「遍历写法」只过了 60%，没写卡在哪。
 *   下面的题干是改编的练习版，不是原题；把矩形设成「可能是斜的」，覆盖最容易丢分的情况。
 *
 * 题目：
 *   给出一个矩形的 4 个顶点，按顺时针或逆时针顺序给出（矩形可能是斜的，边不一定平行于坐标轴）。
 *   再给 q 个点，判断每个点是否在矩形内。点在边上或顶点上也算在内。
 *
 * 输入：
 *   第一行 8 个整数 x1 y1 x2 y2 x3 y3 x4 y4，是矩形 4 个顶点
 *   第二行一个整数 q
 *   接下来 q 行，每行两个整数 x y
 * 输出：q 行，在内输出 IN，否则输出 OUT
 *
 * 样例 1（正的矩形）
 *   输入：
 *     0 0 4 0 4 2 0 2
 *     4
 *     2 1
 *     4 1
 *     5 1
 *     -1 -1
 *   输出：
 *     IN
 *     IN
 *     OUT
 *     OUT
 *   说明：(4,1) 在右边上，算 IN
 *
 * 样例 2（斜 45° 的正方形）
 *   输入：
 *     0 2 2 0 4 2 2 4
 *     5
 *     2 2
 *     0 0
 *     1 1
 *     3 3
 *     4 4
 *   输出：
 *     IN
 *     OUT
 *     IN
 *     IN
 *     OUT
 *   说明：(1,1)、(3,3) 都在边上
 *
 * 数据范围：|坐标| <= 10^9，1 <= q <= 10^5
 *
 * 考点：叉积。点 P 对每条边 AB 算 cross(AB, AP)，4 个结果同号（允许为 0）就在内
 *
 * 自检：
 *   - 坐标到 10^9，叉积是两个差值相乘，int 会溢出，要用 long
 *   - 顶点给的是顺时针还是逆时针都要能判对
 *   - 边上的点（叉积为 0）别判成 OUT
 *   - q 到 10^5，输出用 StringBuilder 或 PrintWriter 一次性打印，别逐行 System.out.println
 *   - 牛客 ACM 模式提交时类名要改成 Main
 */
